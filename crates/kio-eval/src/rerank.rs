#[derive(Debug)]
struct RerankDump {
    note: &'static str,
    limit: usize,
    queries: Vec<DumpedQuery>,
    skipped: Vec<SkippedQuery>,
}

#[derive(Debug)]
struct DumpedQuery {
    id: String,
    scenario: String,
    query: String,
    expected: Vec<ResultKey>,
    baseline_recall_at_10: f64,
    candidates: Vec<Candidate>,
}

#[derive(Debug)]
struct Candidate {
    key: ResultKey,
    text: String,
}

#[derive(Debug)]
struct SkippedQuery {
    query: String,
    reason: String,
}

// Keep the portable dump's established lexicographic wire order without
// materializing a second serde_json::Value tree during pretty rendering.
impl Serialize for RerankDump {
    fn serialize<S: serde::Serializer>(
        &self,
        serializer: S,
    ) -> std::result::Result<S::Ok, S::Error> {
        let mut map = serializer.serialize_map(Some(4))?;
        map.serialize_entry("limit", &self.limit)?;
        map.serialize_entry("note", self.note)?;
        map.serialize_entry("queries", &self.queries)?;
        map.serialize_entry("skipped", &self.skipped)?;
        map.end()
    }
}

impl Serialize for DumpedQuery {
    fn serialize<S: serde::Serializer>(
        &self,
        serializer: S,
    ) -> std::result::Result<S::Ok, S::Error> {
        let mut map = serializer.serialize_map(Some(6))?;
        map.serialize_entry("baseline_recall_at_10", &self.baseline_recall_at_10)?;
        map.serialize_entry("candidates", &self.candidates)?;
        map.serialize_entry("expected", &self.expected)?;
        map.serialize_entry("id", &self.id)?;
        map.serialize_entry("query", &self.query)?;
        map.serialize_entry("scenario", &self.scenario)?;
        map.end()
    }
}

impl Serialize for Candidate {
    fn serialize<S: serde::Serializer>(
        &self,
        serializer: S,
    ) -> std::result::Result<S::Ok, S::Error> {
        let mut map = serializer.serialize_map(Some(2))?;
        map.serialize_entry("key", &self.key)?;
        map.serialize_entry("text", &self.text)?;
        map.end()
    }
}

impl Serialize for SkippedQuery {
    fn serialize<S: serde::Serializer>(
        &self,
        serializer: S,
    ) -> std::result::Result<S::Ok, S::Error> {
        let mut map = serializer.serialize_map(Some(2))?;
        map.serialize_entry("query", &self.query)?;
        map.serialize_entry("reason", &self.reason)?;
        map.end()
    }
}

