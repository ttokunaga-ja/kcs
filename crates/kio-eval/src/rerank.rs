/// Dataset identity is deliberately closed: the synthetic CAS triple and the
/// fixture-B original-filename title are different scoring contracts.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RerankDataset {
    Synthetic,
    FixtureB,
}

impl std::str::FromStr for RerankDataset {
    type Err = String;
    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "synthetic" => Ok(Self::Synthetic),
            "fixture-b" => Ok(Self::FixtureB),
            _ => Err("rerank dataset must be synthetic or fixture-b".into()),
        }
    }
}

