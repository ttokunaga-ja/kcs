//! Immutable-CAS reranker input dump.
//!
//! The GPU differential runs elsewhere, so this command freezes the exact
//! text-lane ordering and the attested chunk text into a portable JSON file.
//! It intentionally accepts only current-tree queries: history queries need a
//! different reconstruction contract and are recorded as skipped.

use std::{
    ffi::{OsStr, OsString},
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use std::collections::{BTreeSet, HashSet};

use serde::{Deserialize, Serialize, ser::SerializeMap};
use thiserror::Error;

