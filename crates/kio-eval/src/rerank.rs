fn current_tree_query(query: &GoldenQuery) -> bool {
    query.flags.is_empty() && query.scenario.required_flag().is_none()
}

fn execute_search(
    bin: &Path,
    scope: &BoundScope,
    environment: &[(OsString, OsString)],
    query: &str,
    limit: usize,
) -> Result<SearchOutcome, String> {
    let mut command = Command::new(bin);
    command
        .arg("--json")
        .arg("search")
        .arg(query)
        .arg("--all-scopes")
        .arg("--limit")
        .arg(limit.to_string())
        .env_clear()
        .envs(environment.iter().cloned());
    scope
        .configure_command_cwd(&mut command)
        .map_err(|error| error.to_string())?;
    let output = run_bounded_command(&mut command, BoundedProcessOptions::default(), None)
        .map_err(|error| error.to_string())?;
    Ok(SearchOutcome {
        returncode: output.status.code().unwrap_or(-1),
        stdout: output.stdout,
        stderr: output.stderr,
        duration_ms: output.duration.as_secs_f64() * 1_000.0,
    })
}

fn execute_fixture_search(
    bin: &Path,
    scope: &Path,
    environment: &[(OsString, OsString)],
    query: &str,
    limit: usize,
) -> Result<SearchOutcome, String> {
    let mut command = Command::new(bin);
    command
        .arg("--json")
        .arg("search")
        .arg(query)
        .arg("--all-scopes")
        .arg("--limit")
        .arg(limit.to_string())
        .current_dir(scope)
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("LANG", "C.UTF-8")
        .env("LC_ALL", "C.UTF-8")
        .env("TZ", "UTC")
        .envs(environment.iter().cloned());
    let output = run_bounded_command(&mut command, BoundedProcessOptions::default(), None)
        .map_err(|error| error.to_string())?;
    Ok(SearchOutcome {
        returncode: output.status.code().unwrap_or(-1),
        stdout: output.stdout,
        stderr: output.stderr,
        duration_ms: output.duration.as_secs_f64() * 1_000.0,
    })
}

fn scored_recall(
    response: &SearchResponse,
    expected: &std::collections::HashSet<ResultKey>,
) -> f64 {
    let results = response
        .results
        .iter()
        .map(|hit| RecallResult {
            raw_hash: hit.pointer.raw_hash.clone(),
            section_id: hit.pointer.section_id.clone(),
            heading_path: hit.pointer.heading_path.clone(),
            path_at_commit: hit.pointer.path_at_commit.clone(),
        })
        .collect::<Vec<_>>();
    recall_at_k(&results, expected, 10)
}

fn render(report: &RerankDump) -> Result<Vec<u8>, RerankDumpError> {
    let mut bytes = serde_json::to_vec_pretty(report)?;
    if bytes.len() > MAX_RERANK_REPORT_BYTES {
        return Err(RerankDumpError::Input(
            "rerank dump exceeds artifact byte limit".into(),
        ));
    }
    bytes.push(b'\n');
    Ok(bytes)
}

fn fixture_title(title: &str) -> String {
    title.strip_suffix(".md").unwrap_or(title).to_owned()
}

/// Reconstruct fixture-B candidate text from the product evidence span.
/// `byte_end == EOF + 1` is an explicit allowed final-chunk convention; any
/// larger overrun or malformed pointer is rejected.
fn fixture_chunk_text(pointer: &serde_json::Value, tree: &Path) -> Result<String, String> {
    let object = pointer
        .as_object()
        .ok_or_else(|| "evidence pointer is not an object".to_owned())?;
    let scope = object
        .get("scope_path")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| "evidence pointer has no scope_path".to_owned())?;
    let relative = object
        .get("path_at_commit")
        .and_then(serde_json::Value::as_str)
        .filter(|s| !s.is_empty())
        .ok_or_else(|| "evidence pointer has no path_at_commit".to_owned())?;
    let start = object
        .get("byte_start")
        .and_then(serde_json::Value::as_u64)
        .ok_or_else(|| "evidence pointer has invalid byte_start".to_owned())?
        as usize;
    let end = object
        .get("byte_end")
        .and_then(serde_json::Value::as_u64)
        .ok_or_else(|| "evidence pointer has invalid byte_end".to_owned())? as usize;
    let tree =
        fs::canonicalize(tree).map_err(|_| "bound fixture tree is unavailable".to_owned())?;
    let scope = fs::canonicalize(scope)
        .map_err(|_| "evidence pointer scope_path is unavailable".to_owned())?;
    if !scope.starts_with(&tree) || scope.file_name().and_then(OsStr::to_str) != Some(".kio") {
        return Err("evidence pointer scope_path is outside the bound fixture tree".into());
    }
    let root = scope
        .parent()
        .ok_or_else(|| "scope_path has no parent".to_owned())?;
    let relative = Path::new(relative);
    if relative.is_absolute()
        || relative
            .components()
            .any(|c| !matches!(c, std::path::Component::Normal(part) if part != ".kio"))
    {
        return Err("evidence pointer has unsafe path_at_commit".into());
    }
    let bytes = kio_core::cas::read_bounded_regular_file(
        &root.join(relative),
        MAX_RERANK_RENDER_SOURCE_BYTES,
    )
    .map_err(|e| format!("cannot reconstruct candidate: {e}"))?;
    if start > end || start > bytes.len() || end > bytes.len().saturating_add(1) {
        return Err("evidence span is outside source bytes (only EOF+1 is allowed)".into());
    }
    std::str::from_utf8(&bytes[start..end.min(bytes.len())])
        .map(str::to_owned)
        .map_err(|_| "candidate text is not UTF-8".into())
}

fn first_fixture_scope(tree: &Path) -> Result<PathBuf, RerankDumpError> {
    let mut scopes = Vec::new();
    let mut todo = vec![tree.to_owned()];
    while let Some(path) = todo.pop() {
        let mut entries = fs::read_dir(&path)
            .map_err(|e| RerankDumpError::Input(format!("cannot walk fixture tree: {e}")))?
            .collect::<Result<Vec<_>, _>>()
            .map_err(|e| RerankDumpError::Input(e.to_string()))?;
        entries.sort_by_key(|e| e.file_name());
        let mut file = false;
        for entry in entries {
            let ty = entry
                .file_type()
                .map_err(|e| RerankDumpError::Input(e.to_string()))?;
            if ty.is_symlink() {
                return Err(RerankDumpError::Input(
                    "fixture tree contains symlink".into(),
                ));
            }
            if ty.is_file() {
                file = true;
            } else if ty.is_dir() && entry.file_name() != ".kio" {
                todo.push(entry.path());
            }
        }
        if file {
            scopes.push(path);
        }
    }
    scopes.sort();
    scopes
        .into_iter()
        .next()
        .ok_or_else(|| RerankDumpError::Input("fixture tree has no direct-file scope".into()))
}

/// Produce the fixture-B dump. This is intentionally separate from synthetic
/// CAS attestation: fixture-B binds candidate identity to the returned title.
pub fn run_fixture_b(
    options: FixtureRerankDumpOptions,
) -> Result<RerankDumpSummary, RerankDumpError> {
    if options.limit != MAX_RERANK_LIMIT {
        return Err(RerankDumpError::Input(format!(
            "fixture-B rerank limit must be exactly {MAX_RERANK_LIMIT}"
        )));
    }
    if options.gemini_api_key.is_empty() {
        return Err(RerankDumpError::Input(
            "fixture-B requires GEMINI_API_KEY to preserve the vector candidate pool".into(),
        ));
    }
    let root = fs::canonicalize(&options.root)
        .map_err(|e| RerankDumpError::Input(format!("cannot open fixture root: {e}")))?;
    let tree = root.join("tree");
    if !tree.is_dir() {
        return Err(RerankDumpError::Input("fixture root has no tree/".into()));
    }
    let destination = CreateOnlyArtifact::bind(&options.out, &root, "fixture rerank output")
        .map_err(|e| RerankDumpError::Input(e.to_string()))?;
    let bin = fs::canonicalize(&options.bin)
        .map_err(|_| RerankDumpError::Input("kio binary unavailable".into()))?;
    if !bin.is_file() {
        return Err(RerankDumpError::Input("kio binary unavailable".into()));
    }
    let scope = first_fixture_scope(&tree)?;
    let mut environment = [
        ("HOME", root.join("h")),
        ("XDG_CONFIG_HOME", root.join("c")),
        ("XDG_DATA_HOME", root.join("d")),
        ("XDG_CACHE_HOME", root.join("k")),
    ]
    .into_iter()
    .map(|(k, v)| (OsString::from(k), v.into_os_string()))
    .collect::<Vec<_>>();
    environment.push((OsString::from("GEMINI_API_KEY"), options.gemini_api_key));
    let golden = kio_core::cas::read_bounded_regular_file(&options.golden, MAX_RERANK_INPUT_BYTES)
        .map_err(|e| RerankDumpError::Input(format!("cannot read fixture golden: {e}")))?;
    let lines = std::str::from_utf8(&golden)
        .map_err(|_| RerankDumpError::Input("fixture golden is not UTF-8".into()))?;
    let mut queries = Vec::new();
    let mut skipped = Vec::new();
    let mut text_budget = FixtureTextBudget::default();
    for line in lines.lines().filter(|line| !line.trim().is_empty()) {
        if queries.len() + skipped.len() >= MAX_RERANK_QUERIES {
            return Err(RerankDumpError::Input(
                "fixture golden has too many queries".into(),
            ));
        }
        let query: FixtureGoldenQuery = serde_json::from_str(line)
            .map_err(|e| RerankDumpError::Input(format!("invalid fixture golden: {e}")))?;
        if !valid_human_string(&query.query_id)
            || !valid_human_string(&query.class)
            || !valid_human_string(&query.query)
        {
            return Err(RerankDumpError::Input(
                "fixture golden has invalid query identity".into(),
            ));
        }
        text_budget.string(&query.query_id)?;
        text_budget.string(&query.class)?;
        text_budget.string(&query.query)?;
        if query.expected.is_empty() || query.expected.len() > MAX_RERANK_LIMIT {
            return Err(RerankDumpError::Input(format!(
                "{} has invalid expected set",
                query.query_id
            )));
        }
        let expected = query
            .expected
            .iter()
            .map(|e| {
                Path::new(&e.path)
                    .file_name()
                    .and_then(OsStr::to_str)
                    .map(|s| vec![s.to_owned()])
                    .ok_or_else(|| {
                        RerankDumpError::Input(format!(
                            "{} has invalid expected path",
                            query.query_id
                        ))
                    })
            })
            .collect::<Result<Vec<_>, _>>()?;
        let response =
            match execute_fixture_search(&bin, &scope, &environment, &query.query, options.limit)
                .and_then(|o| match classify_outcome(&o) {
                    ClassifiedOutcome::Scored { response, .. } => Ok(response),
                    ClassifiedOutcome::Unimplemented { error_code } => {
                        Err(format!("search unimplemented: {error_code}"))
                    }
                    ClassifiedOutcome::Failed { error_code, detail } => {
                        Err(error_code.map_or(detail.clone(), |c| format!("{c}: {detail}")))
                    }
                }) {
                Ok(r) => r,
                Err(reason) => {
                    skipped.push(FixtureSkippedQuery {
                        query_id: query.query_id,
                        reason,
                    });
                    continue;
                }
            };
        let mut candidates = Vec::new();
        let mut missing = 0usize;
        for hit in response.results.iter().take(options.limit) {
            let Some(title) = hit.title.as_deref() else {
                missing += 1;
                continue;
            };
            if !valid_human_string(title) {
                missing += 1;
                continue;
            }
            match fixture_chunk_text(&hit.pointer_value, &tree) {
                Ok(text) if valid_human_string(&text) => {
                    let title = fixture_title(title);
                    text_budget.string(&title)?;
                    text_budget.string(&text)?;
                    candidates.push(FixtureCandidate {
                        key: vec![title],
                        text,
                    });
                }
                _ => missing += 1,
            }
        }
        if missing > 0 {
            skipped.push(FixtureSkippedQuery {
                query_id: query.query_id,
                reason: format!("{missing} candidate(s) not reconstructible"),
            });
            continue;
        }
        if candidates.is_empty() {
            skipped.push(FixtureSkippedQuery {
                query_id: query.query_id,
                reason: "no candidates".into(),
            });
            continue;
        }
        let wanted = expected.iter().cloned().collect::<HashSet<_>>();
        let top = candidates
            .iter()
            .take(10)
            .map(|c| c.key.clone())
            .collect::<HashSet<_>>();
        let baseline = top.intersection(&wanted).count() as f64 / wanted.len() as f64;
        queries.push(FixtureDumpedQuery {
            baseline_recall_at_10: baseline,
            candidates,
            expected,
            id: query.query_id,
            query: query.query,
            scenario: query.class,
        });
    }
    if queries.is_empty() {
        return Err(RerankDumpError::Input(
            "no fixture-B query produced a candidate pool".into(),
        ));
    }
    let baseline_recall_at_10 =
        queries.iter().map(|q| q.baseline_recall_at_10).sum::<f64>() / queries.len() as f64;
    let candidate_count = queries.iter().map(|q| q.candidates.len()).sum();
    let report = FixtureDump {
        limit: options.limit,
        note: FIXTURE_RERANK_DUMP_NOTE,
        queries,
        skipped,
    };
    let mut bytes = serde_json::to_vec_pretty(&report)?;
    bytes.push(b'\n');
    if bytes.len() > MAX_RERANK_REPORT_BYTES {
        return Err(RerankDumpError::Input(
            "fixture rerank dump exceeds artifact byte limit".into(),
        ));
    }
    destination
        .publish(&bytes, MAX_RERANK_REPORT_BYTES)
        .map_err(|e| RerankDumpError::Input(e.to_string()))?;
    Ok(RerankDumpSummary {
        dumped_queries: report.queries.len(),
        skipped_queries: report.skipped.len(),
        candidates: candidate_count,
        baseline_recall_at_10,
        output: destination.public_path().to_owned(),
    })
}

#[derive(Default)]
struct RenderBudget {
    escaped_source_bytes: u64,
}

impl RenderBudget {
    fn charge(&mut self, bytes: u64) -> Result<(), RerankDumpError> {
        self.escaped_source_bytes = self
            .escaped_source_bytes
            .checked_add(bytes)
            .ok_or_else(|| RerankDumpError::Input("rerank dump byte accounting overflow".into()))?;
        if self.escaped_source_bytes > MAX_RERANK_RENDER_SOURCE_BYTES {
            return Err(RerankDumpError::Input(
                "rerank dump exceeds conservative render bound".into(),
            ));
        }
        Ok(())
    }

    fn string(&mut self, value: &str) -> Result<(), RerankDumpError> {
        self.charge(json_string_bytes(value))
    }

    fn key(&mut self, key: &ResultKey) -> Result<(), RerankDumpError> {
        self.charge(32)?;
        self.string(&key.0)?;
        if let Some(value) = &key.1 {
            self.string(value)?;
        }
        if let Some(value) = &key.2 {
            self.string(value)?;
        }
        Ok(())
    }
}

fn retain_skipped(
    skipped: &mut Vec<SkippedQuery>,
    budget: &mut RenderBudget,
    query: String,
    reason: String,
) -> Result<(), RerankDumpError> {
    budget.charge(64)?;
    budget.string(&query)?;
    budget.string(&reason)?;
    skipped.push(SkippedQuery { query, reason });
    Ok(())
}

pub fn run(options: RerankDumpOptions) -> Result<RerankDumpSummary, RerankDumpError> {
    if options.golden.is_empty() {
        return Err(RerankDumpError::Input(
            "at least one rerank golden file is required".into(),
        ));
    }
    if options.golden.len() > MAX_RERANK_GOLDEN_FILES {
        return Err(RerankDumpError::Input(format!(
            "at most {MAX_RERANK_GOLDEN_FILES} rerank golden files are allowed"
        )));
    }
    if !(1..=MAX_RERANK_LIMIT).contains(&options.limit) {
        return Err(RerankDumpError::Input(format!(
            "rerank limit must be in 1..={MAX_RERANK_LIMIT}"
        )));
    }
    let destination = CreateOnlyArtifact::bind(&options.out, &options.corpus, "rerank output")
        .map_err(|error| RerankDumpError::Input(error.to_string()))?;
    let corpus_manifest = load_corpus_manifest(&options.corpus.join("corpus-manifest.json"))?;
    let _history_manifest = load_history_manifest(
        &options.corpus.join("history-manifest.json"),
        &corpus_manifest,
    )?;
    let resolver = Resolver::new(&corpus_manifest);
    let corpus_path = fs::canonicalize(&options.corpus).map_err(|error| {
        RerankDumpError::Input(format!("cannot open synthetic corpus: {error}"))
    })?;
    let corpus = BoundCorpus::bind(&corpus_path, &corpus_manifest.scopes)
        .map_err(|error| RerankDumpError::Input(error.to_string()))?;
    let research = corpus
        .scope("research")
        .ok_or_else(|| RerankDumpError::Input("research scope is unavailable".into()))?;
    let environment = corpus.device().hermetic_environment();
    let bin = fs::canonicalize(&options.bin).map_err(|_| {
        RerankDumpError::Input(format!("kio binary unavailable: {}", options.bin.display()))
    })?;
    if !bin.is_file() {
        return Err(RerankDumpError::Input(format!(
            "kio binary unavailable: {}",
            bin.display()
        )));
    }
    let mut attestor = PointerAttestor::from_bound_corpus(&corpus)
        .map_err(|error| RerankDumpError::Input(error.to_string()))?;
    let mut dumped = Vec::new();
    let mut skipped = Vec::new();
    let mut render_budget = RenderBudget::default();
    let mut loaded_queries = 0_usize;
    for golden in &options.golden {
        let file_name = golden
            .file_name()
            .and_then(OsStr::to_str)
            .ok_or_else(|| RerankDumpError::Input("golden path has no UTF-8 filename".into()))?;
        for (index, query) in load_golden_queries(golden)?.into_iter().enumerate() {
            loaded_queries = loaded_queries
                .checked_add(1)
                .ok_or_else(|| RerankDumpError::Input("rerank dump query count overflow".into()))?;
            if loaded_queries > MAX_RERANK_QUERIES {
                return Err(RerankDumpError::Input(
                    "rerank dump has too many queries across golden files".into(),
                ));
            }
            if !current_tree_query(&query) {
                retain_skipped(
                    &mut skipped,
                    &mut render_budget,
                    query.query,
                    format!("history query ({})", query.scenario.as_str()),
                )?;
                continue;
            }
            let (expected, errors) = resolver.resolve_expected(&query.expected);
            if !errors.is_empty() || expected.is_empty() {
                retain_skipped(
                    &mut skipped,
                    &mut render_budget,
                    query.query,
                    format!(
                        "expected unresolved: {}",
                        errors
                            .iter()
                            .map(ToString::to_string)
                            .collect::<Vec<_>>()
                            .join("; ")
                    ),
                )?;
                continue;
            }
            let outcome =
                match execute_search(&bin, research, &environment, &query.query, options.limit) {
                    Ok(outcome) => outcome,
                    Err(reason) => {
                        retain_skipped(&mut skipped, &mut render_budget, query.query, reason)?;
                        continue;
                    }
                };
            let response = match classify_outcome(&outcome) {
                ClassifiedOutcome::Scored { response, .. } => response,
                ClassifiedOutcome::Unimplemented { error_code } => {
                    retain_skipped(
                        &mut skipped,
                        &mut render_budget,
                        query.query,
                        format!("search unimplemented: {error_code}"),
                    )?;
                    continue;
                }
                ClassifiedOutcome::Failed { error_code, detail } => {
                    retain_skipped(
                        &mut skipped,
                        &mut render_budget,
                        query.query,
                        error_code.map_or(detail.clone(), |code| format!("{code}: {detail}")),
                    )?;
                    continue;
                }
            };
            let mut candidates = Vec::new();
            let mut missing = Vec::new();
            for hit in response.results.iter().take(options.limit) {
                match attestor.attest_current_chunk_text(&hit.pointer_value) {
                    Ok(text) => {
                        let key = hit.result_key();
                        render_budget.charge(64)?;
                        render_budget.key(&key)?;
                        render_budget.string(&text)?;
                        candidates.push(Candidate { key, text });
                    }
                    Err(error) => missing.push(error.to_string()),
                }
            }
            if !missing.is_empty() {
                retain_skipped(
                    &mut skipped,
                    &mut render_budget,
                    query.query,
                    format!(
                        "{} candidate(s) not reconstructible: {}",
                        missing.len(),
                        missing[0]
                    ),
                )?;
                continue;
            }
            if candidates.is_empty() {
                retain_skipped(
                    &mut skipped,
                    &mut render_budget,
                    query.query,
                    "no candidates".into(),
                )?;
                continue;
            }
            let baseline_recall_at_10 = scored_recall(&response, &expected);
            let mut expected = expected.into_iter().collect::<Vec<_>>();
            expected.sort();
            let id = format!("{file_name}#{index}");
            render_budget.charge(128)?;
            render_budget.string(&id)?;
            render_budget.string(query.scenario.as_str())?;
            render_budget.string(&query.query)?;
            render_budget.charge(expected.len() as u64 * 32)?;
            for key in &expected {
                render_budget.key(key)?;
            }
            dumped.push(DumpedQuery {
                id,
                scenario: query.scenario.as_str().to_owned(),
                query: query.query,
                expected,
                baseline_recall_at_10,
                candidates,
            });
        }
    }
    if dumped.is_empty() {
        let detail = skipped
            .first()
            .map(|query| format!(": {}", query.reason))
            .unwrap_or_default();
        return Err(RerankDumpError::Input(format!(
            "no current-tree rerank query produced an attested candidate pool{detail}"
        )));
    }
    let baseline_recall_at_10 = dumped
        .iter()
        .map(|query| query.baseline_recall_at_10)
        .sum::<f64>()
        / dumped.len() as f64;
    let candidate_count = dumped.iter().map(|query| query.candidates.len()).sum();
    let report = RerankDump {
        note: RERANK_DUMP_NOTE,
        limit: options.limit,
        queries: dumped,
        skipped,
    };
    let summary = RerankDumpSummary {
        dumped_queries: report.queries.len(),
        skipped_queries: report.skipped.len(),
        candidates: candidate_count,
        baseline_recall_at_10,
        output: destination.public_path().to_path_buf(),
    };
    destination
        .publish(&render(&report)?, MAX_RERANK_REPORT_BYTES)
        .map_err(|error| RerankDumpError::Input(error.to_string()))?;
    Ok(summary)
}

fn read_apply_json<T: for<'de> Deserialize<'de>>(
    path: &Path,
    label: &str,
) -> Result<T, RerankApplyError> {
    let bytes = kio_core::cas::read_bounded_regular_file(path, MAX_RERANK_INPUT_BYTES)
        .map_err(|error| RerankApplyError::Input(format!("cannot read {label}: {error}")))?;
    serde_json::from_slice(&bytes).map_err(RerankApplyError::from)
}

fn validate_key(key: &ApplyKey, arity: usize, label: &str) -> Result<(), RerankApplyError> {
    if key.len() != arity || key.is_empty() || key[0].as_deref().is_none_or(str::is_empty) {
        return Err(RerankApplyError::Input(format!(
            "{label} has an invalid result key"
        )));
    }
    if key.iter().flatten().any(String::is_empty) {
        return Err(RerankApplyError::Input(format!(
            "{label} has an empty result-key component"
        )));
    }
    Ok(())
}

fn valid_human_string(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= MAX_RERANK_STRING_BYTES
        && !value.chars().any(char::is_control)
}

fn json_string_bytes(value: &str) -> u64 {
    value.bytes().fold(2_u64, |total, byte| {
        total.saturating_add(match byte {
            b'\"' | b'\\' => 2,
            0..=0x1f => 6,
            _ => 1,
        })
    })
}

fn validate_apply_dump(dump: &ApplyDump) -> Result<(), RerankApplyError> {
    if dump.note != RERANK_DUMP_NOTE && dump.note != FIXTURE_RERANK_DUMP_NOTE {
        return Err(RerankApplyError::Input(
            "rerank dump note is not current".into(),
        ));
    }
    if !(1..=MAX_RERANK_LIMIT).contains(&dump.limit) {
        return Err(RerankApplyError::Input(format!(
            "rerank dump limit must be in 1..={MAX_RERANK_LIMIT}"
        )));
    }
    if dump.queries.is_empty() {
        return Err(RerankApplyError::Input("rerank dump has no queries".into()));
    }
    if dump.queries.len() > MAX_RERANK_QUERIES {
        return Err(RerankApplyError::Input(
            "rerank dump has too many queries".into(),
        ));
    }
    if dump.skipped.len() > MAX_RERANK_QUERIES {
        return Err(RerankApplyError::Input(
            "rerank dump has too many skipped queries".into(),
        ));
    }
    for skipped in &dump.skipped {
        let (id, reason) = match skipped {
            ApplySkippedQuery::Synthetic { query, reason } => (query, reason),
            ApplySkippedQuery::Fixture { query_id, reason } => (query_id, reason),
        };
        if !valid_human_string(id) || !valid_human_string(reason) {
            return Err(RerankApplyError::Input(
                "rerank dump has an invalid skipped query".into(),
            ));
        }
    }
    let required_arity = if dump.note == RERANK_DUMP_NOTE { 3 } else { 1 };
    let mut ids = BTreeSet::new();
    for query in &dump.queries {
        if !valid_human_string(&query.id) {
            return Err(RerankApplyError::Input(
                "rerank dump has an invalid query id".into(),
            ));
        }
        if !ids.insert(&query.id) {
            return Err(RerankApplyError::Input(
                "rerank dump has a duplicate query id".into(),
            ));
        }
        if !valid_human_string(&query.scenario)
            || !valid_human_string(&query.query)
            || query.expected.is_empty()
        {
            return Err(RerankApplyError::Input(format!(
                "{} has missing required query fields",
                query.id
            )));
        }
        if !query.baseline_recall_at_10.is_finite()
            || !(0.0..=1.0).contains(&query.baseline_recall_at_10)
        {
            return Err(RerankApplyError::Input(format!(
                "{} has invalid baseline Recall@10",
                query.id
            )));
        }
        if query.candidates.is_empty() || query.candidates.len() > dump.limit {
            return Err(RerankApplyError::Input(format!(
                "{} candidate count is outside the dump limit",
                query.id
            )));
        }
        let arity =
            query.expected.first().map(Vec::len).ok_or_else(|| {
                RerankApplyError::Input(format!("{} has no expected keys", query.id))
            })?;
        if arity != required_arity {
            return Err(RerankApplyError::Input(format!(
                "{} key arity does not match its producer contract",
                query.id
            )));
        }
        if query.expected.iter().collect::<HashSet<_>>().len() != query.expected.len() {
            return Err(RerankApplyError::Input(format!(
                "{} contains duplicate expected keys",
                query.id
            )));
        }
        for key in &query.expected {
            validate_key(key, arity, &format!("{} expected key", query.id))?;
        }
        for candidate in &query.candidates {
            validate_key(
                &candidate.key,
                arity,
                &format!("{} candidate key", query.id),
            )?;
        }
        let expected = query.expected.iter().cloned().collect::<HashSet<_>>();
        let observed = query
            .candidates
            .iter()
            .map(|candidate| &candidate.key)
            .collect::<Vec<_>>();
        let calculated = apply_recall_at_10(&observed, &expected);
        if (calculated - query.baseline_recall_at_10).abs() > f64::EPSILON {
            return Err(RerankApplyError::Input(format!(
                "{} baseline Recall@10 does not match candidates",
                query.id
            )));
        }
    }
    Ok(())
}

fn apply_recall_at_10(keys: &[&ApplyKey], expected: &HashSet<ApplyKey>) -> f64 {
    if expected.is_empty() {
        return 0.0;
    }
    let got = keys
        .iter()
        .take(10)
        .map(|key| (*key).clone())
        .collect::<HashSet<_>>();
    got.intersection(expected).count() as f64 / expected.len() as f64
}

fn render_apply_report(report: &ApplyReport<'_>) -> Result<Vec<u8>, RerankApplyError> {
    let mut bytes = serde_json::to_vec_pretty(report)?;
    if bytes.len() > MAX_RERANK_REPORT_BYTES {
        return Err(RerankApplyError::Input(
            "rerank report exceeds artifact byte limit".into(),
        ));
    }
    bytes.push(b'\n');
    Ok(bytes)
}

pub fn apply(options: RerankApplyOptions) -> Result<RerankApplySummary, RerankApplyError> {
    let dump: ApplyDump = read_apply_json(&options.input, "rerank dump")?;
    validate_apply_dump(&dump)?;
    let output: RerankOutput = read_apply_json(&options.output, "rerank output")?;
    if !valid_human_string(&output.model) || output.model.trim().is_empty() {
        return Err(RerankApplyError::Input(
            "rerank output model is empty".into(),
        ));
    }

    let known_ids = dump
        .queries
        .iter()
        .map(|query| &query.id)
        .collect::<HashSet<_>>();
    let mut rankings = std::collections::BTreeMap::new();
    let mut problems = Vec::new();
    for output_query in &output.queries {
        if !valid_human_string(&output_query.id) {
            return Err(RerankApplyError::Input(
                "rerank output has an invalid query id".into(),
            ));
        }
        if !known_ids.contains(&output_query.id) {
            problems.push(format!("{}: unknown rerank output id", output_query.id));
            continue;
        }
        if rankings
            .insert(&output_query.id, &output_query.ranking)
            .is_some()
        {
            problems.push(format!("{}: duplicate rerank output id", output_query.id));
        }
    }

    let mut rows = Vec::new();
    let mut ranked_queries = 0;
    let mut improved = 0;
    let mut worsened = 0;
    for query in &dump.queries {
        let expected = query.expected.iter().cloned().collect::<HashSet<_>>();
        let before = query.baseline_recall_at_10;
        let Some(ranking) = rankings.get(&query.id) else {
            problems.push(format!("{}: absent from the rerank output", query.id));
            rows.push(ApplyReportQuery {
                id: &query.id,
                query: &query.query,
                candidates: query.candidates.len(),
                before,
                after: before,
                state: "unranked",
            });
            continue;
        };
        let mut seen = HashSet::new();
        if ranking.is_empty() {
            problems.push(format!("{}: ranking is empty", query.id));
            rows.push(ApplyReportQuery {
                id: &query.id,
                query: &query.query,
                candidates: query.candidates.len(),
                before,
                after: before,
                state: "unranked",
            });
            continue;
        }
        let mut order = Vec::with_capacity(query.candidates.len());
        let mut invalid = None;
        for &index in *ranking {
            if index >= query.candidates.len() {
                invalid = Some(format!("ranking index {index} is not a candidate"));
                break;
            }
            if !seen.insert(index) {
                invalid = Some(format!("ranking repeats index {index}"));
                break;
            }
            order.push(index);
        }
        if let Some(error) = invalid {
            problems.push(format!("{}: {error}", query.id));
            rows.push(ApplyReportQuery {
                id: &query.id,
                query: &query.query,
                candidates: query.candidates.len(),
                before,
                after: before,
                state: "invalid",
            });
            continue;
        }
        order.extend((0..query.candidates.len()).filter(|index| !seen.contains(index)));
        let reranked = order
            .into_iter()
            .map(|index| &query.candidates[index].key)
            .collect::<Vec<_>>();
        let after = apply_recall_at_10(&reranked, &expected);
        ranked_queries += 1;
        improved += usize::from(after > before);
        worsened += usize::from(after < before);
        rows.push(ApplyReportQuery {
            id: &query.id,
            query: &query.query,
            candidates: query.candidates.len(),
            before,
            after,
            state: "ranked",
        });
    }
    let before_recall_at_10 = rows.iter().map(|row| row.before).sum::<f64>() / rows.len() as f64;
    let after_recall_at_10 = rows.iter().map(|row| row.after).sum::<f64>() / rows.len() as f64;
    let report = options
        .report
        .as_ref()
        .map(|path| {
            let destination = CreateOnlyArtifact::bind(path, &options.input, "rerank report")
                .map_err(|error| RerankApplyError::Input(error.to_string()))?;
            let rendered = render_apply_report(&ApplyReport {
                summary: ApplyReportSummary {
                    before: before_recall_at_10,
                    after: after_recall_at_10,
                    improved,
                    worsened,
                    model: &output.model,
                    ranked_queries,
                },
                queries: rows,
                problems: &problems,
            })?;
            destination
                .publish(&rendered, MAX_RERANK_REPORT_BYTES)
                .map_err(|error| RerankApplyError::Input(error.to_string()))?;
            Ok::<_, RerankApplyError>(destination.public_path().to_path_buf())
        })
        .transpose()?;
    Ok(RerankApplySummary {
        model: output.model,
        queries: dump.queries.len(),
        ranked_queries,
        before_recall_at_10,
        after_recall_at_10,
        improved,
        worsened,
        problems,
        report,
    })
}

